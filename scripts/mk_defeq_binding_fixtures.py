#!/usr/bin/env python3
"""Generate the sources of the binder-telescope congruence fixtures (task #520).

    scripts/mk_defeq_binding_fixtures.py OUTDIR [n K N]

writes three Lean sources (defaults n = 40, K = 100, N = 10, the sizes
committed under tests/e2e/src/; larger ones are measurement inputs):

* `defeq_binding_pi.lean` — `w : (∀ x1 … xn : Nat, B) = (∀ x1 … xn : Nat, B')
  := rfl`, where `B` is a K-fold conjunction `P j (x1 + … + xn)` and `B'`
  is `B` with `Q` (`:= P`) in its last conjunct: the two telescopes are
  defeq only after a delta step at the bottom, so the check walks the
  whole Π-type congruence, every conjunct mentioning every binder.
* `defeq_binding_lam.lean` — the same with `fun` in place of `∀`.
* `defeq_binding_mutual.lean` — a mutual block of N structures nested
  through `Array`, `Option` and `String` (the shape of lean4's
  `tests/elab_bench/deriving_mutual_block.lean` without its `deriving`
  clauses); its `brecOn.go`/`brecOn.eq` declarations are long telescopes
  over large bodies, exported with their dependencies.

Each source carries its `--#export` line; `scripts/export-fixture.sh`
turns it into the `.ndjson` stream.
"""
import os
import sys


def synthetic(kind, n, k):
    xs = " ".join(f"x{i}" for i in range(1, n + 1))
    s = " + ".join(f"x{i}" for i in range(1, n + 1))

    def body(last):
        return " ∧ ".join([f"P {j} ({s})" for j in range(1, k)] + [f"{last} {k} ({s})"])

    b, sep = ("∀", ",") if kind == "pi" else ("fun", " =>")
    what = "Π-type" if kind == "pi" else "lambda-expression"
    return f"""--#export w
/-! Task #520 (generated by scripts/mk_defeq_binding_fixtures.py, n = {n}, K = {k}):
the congruence of two {what} telescopes of n binders over a body of K
conjuncts, each mentioning every binder; the bodies are defeq only after
unfolding `Q` in the last conjunct. -/
set_option maxRecDepth 100000

def P (j a : Nat) : Prop := a = j
def Q (j a : Nat) : Prop := P j a

theorem w :
    ({b} {xs} : Nat{sep} {body('P')}) =
    ({b} {xs} : Nat{sep} {body('Q')}) := rfl
"""


def mutual(n):
    names = ["H.brecOn.eq", "H.brecOn_1.eq", "H.brecOn_2.eq", "H2.brecOn.eq"]
    names += [f"T{i}.brecOn.eq" for i in range(n)]
    s = f"--#export {' '.join(names)}\n"
    s += f"""/-! Task #520 (generated by scripts/mk_defeq_binding_fixtures.py, N = {n}):
a mutual block of N structures nested through `Array`, `Option` and
`String` (lean4's `tests/elab_bench/deriving_mutual_block.lean` without
`deriving`); exported are the `brecOn` families, whose `go` definitions
and `eq` theorems are long telescopes over large bodies. -/
set_option maxHeartbeats 0
structure Meta where
  a : Nat

mutual
inductive H where
"""
    s += "".join(f"  | c{i} : T{i} → H\n" for i in range(n))
    s += "  | other (a : Option Meta) (s : String) : H\n"
    s += "structure H2 where\n  p : Option Meta := none\n  f1 : H\n  f2 : String\n"
    for i in range(n):
        s += f"structure T{i} where\n  p : Option Meta := none\n  f1 : H\n  f2 : Array H2\n"
    s += "end\n"
    return s


def main():
    out = sys.argv[1]
    n, k, big_n = (int(a) for a in sys.argv[2:5]) if len(sys.argv) >= 5 else (40, 100, 10)
    files = {
        "defeq_binding_pi.lean": synthetic("pi", n, k),
        "defeq_binding_lam.lean": synthetic("lam", n, k),
        "defeq_binding_mutual.lean": mutual(big_n),
    }
    for name, text in files.items():
        with open(os.path.join(out, name), "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
