#!/usr/bin/env python3
"""Line statistics of the Lean sources, by area and by kind.

    scripts/code-stats.py [REV ...]        # default: the working tree
    scripts/code-stats.py master port-342  # a table per revision, plus the change

Every line of every `.lean` file under `ConLeche/` (and `Main.lean`) is
classified as

  * blank,
  * comment  — inside `--`, `/- … -/` or a docstring `/-- … -/`,
  * proof    — any other line of a `theorem` / `lemma` / `example`
               declaration (statement and proof),
  * code     — any other line (definitions, structures, inductives,
               instances, and the `namespace`/`open`/`variable`/`import`
               lines between declarations).

The classification is lexical: a declaration runs from its header line
(after optional attributes and modifiers) to the next line that starts a
new top-level command at column 0.  It is an approximation, but a
stable one, so comparisons between revisions are meaningful.

Areas:
  kernel, cached, frontend, driver — the executed checker
             (ConLeche/{Kernel,Cached,Frontend,Driver}, Main.lean);
             the row "checker" sums them
  proofs   — everything else under ConLeche/ (the statement, the theory, the proofs)
  fragment — whitepaper/Fragment (the paper's own Lean development)

    scripts/code-stats.py --executed [--files]

adds the column "executed": the code lines inside the source range of a
declaration the shipped binary can run.  It builds `con-leche` in the
current checkout and runs `scripts/executed-decls.lean`, which walks the
compiled IR from `main` (so `@[csimp]`, `@[implemented_by]` and
`@[extern]` count as the compiler resolved them: the fast twin is
executed, the reference body it replaces is not) and maps each reached
IR declaration back to its source declaration.  The pure specification
checker under `ConLeche/Kernel/`, referenced only by proofs and by the
subtypes in signatures, is therefore not counted.  It measures the
working tree only; for another revision, run it in a worktree of that
revision.  `--files` adds the per-file numbers.

Limits: a declaration counts whole once anything of it is reached (a
reached `match` arm or `_lambda` counts its parent's every line), and
IR is reachability, not coverage; code generated by an elaboration-time
splice (the Nat-op pins, the basis tables) has no source range and is
listed, not counted; Lean's own library is out of scope.
"""
import os
import json
import re
import subprocess
import sys

AREAS = [
    ("kernel", ("ConLeche/Kernel/",)),
    ("cached", ("ConLeche/Cached/",)),
    ("frontend", ("ConLeche/Frontend/",)),
    ("driver", ("ConLeche/Driver/", "Main.lean")),
    ("proofs", ("ConLeche/",)),
    ("fragment", ("whitepaper/Fragment/",)),
]

MODS = r"(?:@\[[^\]]*\]\s*)*(?:(?:private|protected|public|noncomputable|partial|unsafe|nonrec|meta|scoped|local)\s+)*"
PROOF_START = re.compile(r"^" + MODS + r"(?:theorem|lemma|example)\b")
CMD_START = re.compile(r"^(?:@\[|[a-z#])")  # any top-level command at column 0


def area_of(path):
    for name, prefixes in AREAS:
        if any(path == p or path.startswith(p) for p in prefixes):
            return name
    return None


def classify(text):
    """Return counts {blank, comment, proof, code} for one file."""
    counts = dict(blank=0, comment=0, proof=0, code=0)
    for kind in line_kinds(text):
        counts[kind] += 1
    return counts


def line_kinds(text):
    """The kind of each line of one file, in order."""
    kinds = []
    depth = 0          # block-comment nesting
    in_proof = False
    for line in text.splitlines():
        stripped = line.strip()
        # block comments (nested), line by line
        if depth > 0 or stripped.startswith("/-"):
            i = 0
            had_code = False
            s = line
            while i < len(s):
                if s.startswith("/-", i):
                    depth += 1; i += 2; continue
                if s.startswith("-/", i) and depth > 0:
                    depth -= 1; i += 2; continue
                if depth == 0 and not s[i].isspace():
                    had_code = True
                    break
                i += 1
            if not had_code:
                kinds.append("comment")
                continue
        if not stripped:
            kinds.append("blank")
            continue
        if stripped.startswith("--"):
            kinds.append("comment")
            continue
        if line[:1] and not line[0].isspace() and CMD_START.match(line):
            in_proof = bool(PROOF_START.match(line))
        kinds.append("proof" if in_proof else "code")
    return kinds


def files_at(rev):
    if rev is None:
        out = subprocess.run(["git", "ls-files"], capture_output=True, text=True, check=True).stdout
    else:
        out = subprocess.run(["git", "ls-tree", "-r", "--name-only", rev],
                             capture_output=True, text=True, check=True).stdout
    return [f for f in out.splitlines() if f.endswith(".lean") and area_of(f)]


def read(rev, path):
    if rev is None:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    return subprocess.run(["git", "show", f"{rev}:{path}"], capture_output=True,
                          text=True, check=True).stdout


def executed_lines():
    """{path: set of 1-based line numbers} of the declarations the binary
    can run, from `scripts/executed-decls.lean` on a fresh build of the
    working tree; plus {module: count} of reached IR declarations of ours
    with no source range (generated by an elaboration-time splice)."""
    log = "_tmp/code-stats-exec-build.log"
    os.makedirs("_tmp", exist_ok=True)
    with open(log, "w") as fh:
        r = subprocess.run(["lake", "build", "con-leche"], stdout=fh, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        sys.exit(f"code-stats: `lake build con-leche` failed (exit {r.returncode}), see {log}")
    r = subprocess.run(["lake", "env", "lean", "--run", "scripts/executed-decls.lean"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"code-stats: executed-decls failed (exit {r.returncode}):\n{r.stderr}")
    lines, unattributed = {}, {}
    for row in r.stdout.splitlines():
        _ir, src, mod, start, end = row.split("\t")
        if src == "?":
            unattributed[mod] = unattributed.get(mod, 0) + 1
            continue
        path = mod.replace(".", "/") + ".lean"
        lines.setdefault(path, set()).update(range(int(start), int(end) + 1))
    return lines, unattributed


def stats(rev, executed=None, per_file=None):
    table = {name: dict(files=0, blank=0, comment=0, proof=0, code=0, executed=0)
             for name, _ in AREAS}
    for f in files_at(rev):
        a = area_of(f)
        kinds = line_kinds(read(rev, f))
        table[a]["files"] += 1
        for k in kinds:
            table[a][k] += 1
        if executed is not None:
            ex = executed.get(f, set())
            n = sum(1 for i, k in enumerate(kinds, 1) if k == "code" and i in ex)
            table[a]["executed"] += n
            if per_file is not None:
                per_file.append((f, kinds.count("code"), n))
    table["checker"] = {k: sum(table[n][k] for n in CHECKER) for k in table["kernel"]}
    return table


CHECKER = ("kernel", "cached", "frontend", "driver")

# The checker by COMPONENT (for `--executed`): first matching prefix wins.
COMPONENTS = [
    ("parser", ("ConLeche/Frontend/",)),
    ("inductive installer", ("ConLeche/Kernel/Inductives/",)),
    ("pinned basis & Nat ops", ("ConLeche/Kernel/Basis", "ConLeche/Kernel/NatOp",
                                "ConLeche/Kernel/StdAxioms", "ConLeche/Kernel/Trust")),
    ("core (whnf, defeq, infer)", ("ConLeche/Kernel/Core", "ConLeche/Kernel/PropRead",
                                   "ConLeche/Kernel/TypeChecker", "ConLeche/Cached/CoreC")),
    ("declaration checking", ("ConLeche/Kernel/Check", "ConLeche/Kernel/DeclCheck",
                              "ConLeche/Cached/CheckerC", "ConLeche/Cached/Decls",
                              "ConLeche/Cached/StreamIndex",
                              "ConLeche/Cached/InstallSkel", "ConLeche/Cached/ParsedC")),
    ("terms & environment", ("ConLeche/Kernel/", "ConLeche/Cached/")),
    ("driver", ("ConLeche/Driver/", "Main.lean")),
]


def component_of(path):
    for name, prefixes in COMPONENTS:
        if any(path == p or path.startswith(p) for p in prefixes):
            return name
    return None


def components(per_file):
    """{component: {files, code, executed}} over the checker's files."""
    out = {name: dict(files=0, code=0, executed=0) for name, _ in COMPONENTS}
    for f, c, n in per_file:
        comp = component_of(f)
        if comp is None:
            continue
        out[comp]["files"] += 1
        out[comp]["code"] += c
        out[comp]["executed"] += n
    out["total"] = {k: sum(v[k] for v in list(out.values())) for k in ("files", "code", "executed")}
    return out


def show_components(label, comps):
    print(f"## {label}: the checker by component")
    print("| component | files | code | executed |")
    print("|---|---:|---:|---:|")
    for name in [n for n, _ in COMPONENTS] + ["total"]:
        r = comps[name]
        print(f"| {name} | {r['files']:,} | {r['code']:,} | {r['executed']:,} |")
    print()
ROWS = CHECKER + ("checker", "proofs", "fragment")
COLS = ("files", "code", "proof", "comment", "blank")


def show(label, table, cols=COLS):
    print(f"## {label}")
    print(f"| area | {' | '.join(cols)} |")
    print("|---|" + "---:|" * len(cols))
    for name in ROWS:
        row = table[name]
        print(f"| {name} | " + " | ".join(f"{row[c]:,}" for c in cols) + " |")
    print()


def main(argv):
    if "--executed" in argv:
        json_out = None
        if "--json" in argv:
            i = argv.index("--json")
            json_out = argv[i + 1]
            argv = argv[:i] + argv[i + 2:]
        rest = [a for a in argv if a not in ("--executed", "--files")]
        if rest:
            sys.exit("code-stats: --executed measures the working tree only "
                     "(run it in a checkout or worktree of the revision)")
        executed, unattributed = executed_lines()
        per_file = []
        table = stats(None, executed, per_file)
        show("working tree", table, COLS[:2] + ("executed",) + COLS[2:])
        comps = components(per_file)
        show_components("working tree", comps)
        if json_out:
            with open(json_out, "w") as fh:
                json.dump({"areas": table, "components": comps}, fh, indent=1)
        if unattributed:
            print("Reached IR declarations with no source range (generated by a splice; "
                  "not counted):")
            for mod, n in sorted(unattributed.items(), key=lambda x: -x[1]):
                print(f"  {n:6,}  {mod}")
            print()
        if "--files" in argv:
            print("| file | code | executed |")
            print("|---|---:|---:|")
            for f, c, n in per_file:
                if area_of(f) in CHECKER or n:
                    print(f"| {f} | {c:,} | {n:,} |")
        return
    revs = argv or [None]
    tables = [(r or "working tree", stats(r)) for r in revs]
    for label, t in tables:
        show(label, t)
    if len(tables) >= 2:
        (la, a), (lb, b) = tables[0], tables[-1]
        print(f"## change {la} → {lb}")
        print(f"| area | {' | '.join(COLS)} |")
        print("|---|" + "---:|" * len(COLS))
        for name in ROWS:
            cells = []
            for c in COLS:
                x, y = a[name][c], b[name][c]
                pct = f" ({(y - x) / x:+.1%})" if x else ""
                cells.append(f"{y - x:+,}{pct}")
            print(f"| {name} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main(sys.argv[1:])
